-- ===========================================================================
-- 7.4.1.1 调整单管理（补）：调整单行补一个**行序号** line_no
-- ===========================================================================
--
-- 蓝图原文：「**发起库存调整**（盘盈盘亏、损坏、报废、错发纠正、平台仓差异），填写原因与凭证，
-- **支持批量调整**。」
--
-- ---------------------------------------------------------------------------
-- 一、为什么现在才补这一列：问题不是「没排序」，是「排序键本身没有含义」
-- ---------------------------------------------------------------------------
-- V260 建表时 inventory_adjustment_order_line 的主键是**随机 uuid（v4）**，
-- 而服务层两处读行都按它排序：
--   - 调整单详情读行：      order by l.id
--   - 过账前的行预检：      order by l.id
--
-- 随机 UUID 的**大小顺序与加行顺序毫无关系** ⇒ 同一张单的两行谁在前**每次都可能不一样**。
-- 对外表现：批量调整单的明细行会在两次请求之间**自己换位置**，
-- 审批人看到的「第 1 行」未必是操作员提交的「第 1 行」——
-- 「按单据逐行核对」这条动作链在单据自己换顺序时是不成立的。
--
-- 2026-10-21 19:36 集成头全量 verify，warehouse 1612 例里红的就是这条：
-- 断言 lines.get(0) 是 A-01，服务返回的 get(0) 恰好是 A-02 ⇒ 约 50% 概率的假红
-- （上一轮 L2 同一断言是绿的 ⇒ 典型偶发，不是稳定缺陷）。
--
-- ---------------------------------------------------------------------------
-- 二、为什么是「行序号」，而不是「按业务键排」
-- ---------------------------------------------------------------------------
-- 次选方案是把 ORDER BY 改成 (sku_code, location_code, lot_code, l.id)：
-- 顺序确实确定了，但含义变成「按 SKU / 库位 / 批次排」，而不是「按加行顺序」。
-- 批量调整单里操作员给的顺序本身有业务含义（按货架走、按清点顺序），
-- 排序键必须能表达它，否则「审批人看到的顺序 = 操作员提交的顺序」这条链就断了。
--
-- 行序号是本仓既有口径（V117 recount_line.line_no、V213 logistics_cost_allocation_line.line_no、
-- V254 purchase_order_line.line_no 都是同一写法）：单内从 1 递增 + UNIQUE(单头, line_no)。
--
-- ---------------------------------------------------------------------------
-- 三、跨车道影响面：这张表是**本模块自己的**，没有别的车道拥有它
-- ---------------------------------------------------------------------------
-- inventory_adjustment_order_line 由 V260（本批次 2026-10-21 新建，尚未推送）创建，
-- 全仓只有本模块的两个写入方（InventoryAdjustmentService + 本模块的租户隔离测试夹具），
-- 两个都在本车道内同步改好 ⇒ 本次 ALTER 不构成跨车道 DDL 回归。
--
-- **零 ALTER 既有表**：stock_bucket / inventory_balance / stocktake_variance_* 一律没碰；
-- 本迁移只动 inventory_adjustment_order_line 这一张本批次新建的表。
--
-- ---------------------------------------------------------------------------
-- 四、NOT NULL 与默认值怎么兜底（本仓反复出事的那个形状）
-- ---------------------------------------------------------------------------
-- 纪律：不能出现「加了 NOT NULL 列却不给默认值 ⇒ 别人的老 INSERT 必违约」。
-- 本次按 identity V6（department.code）同一条口径做四步，且**全程在一个事务里**
-- （PG 的 DDL 是事务性的 ⇒ 迁移窗口内没有任何并发会话能看见中间态）：
--
--   1. ADD COLUMN ... NOT NULL DEFAULT 0 —— 加列这一刻在任何已有数据上都不会失败；
--   2. 回填：同一张单内按 row_number() 给历史行一个确定且唯一的序号；
--   3. DROP DEFAULT —— 之后任何 INSERT 都**必须显式**给行号；
--   4. 加 CHECK(line_no > 0) 与 UNIQUE(tenant_id, order_id, line_no)。
--
-- 为什么第 3 步**不留**默认值：留一个「魔法默认值 1」会让漏写行号的 INSERT 静默拿到 1
-- ⇒ 同单第二行撞 UNIQUE（报一个看不懂的错），更糟的是单行单悄悄排到了最前面。
-- 本表只有一个业务写入方（本模块的服务层，已同步改成显式给行号），
-- 所以「必须显式给」是安全的，而且漏给时报的是**响亮的 23502 not-null violation**，
-- 不是一行含义错掉的明细。
--
-- ---------------------------------------------------------------------------
-- 五、并发加行怎么保证不撞号
-- ---------------------------------------------------------------------------
-- 服务层：加行前先**锁住单头**（select ... for update）再取 max(line_no)+1
-- ⇒ 同一张单的并发加行排队执行，拿到互不相同的行号；
-- 建单时（同一个事务、同一张单还没提交给别的会话）行号按输入顺序直接 1..n 赋值。
--
-- DB 层：UNIQUE(tenant_id, order_id, line_no) 是**最终保证** ——
-- 就算有人绕过服务层直接 INSERT，同单两行同号也进不来（23505），不会静默重号。
--
-- 删行**不重排**：行号只增不减（删掉第 2 行后第 3 行仍是 3）。
-- 重排会改写已过账行的意义（V260 的 guard_inventory_adjustment_line_posted 也不许改行），
-- 而且删行之后留一个空号，比「行号连续」更诚实：它如实说「这里原本有过第 2 行」。
--
-- ---------------------------------------------------------------------------
-- 六、行号**不进 API 契约**
-- ---------------------------------------------------------------------------
-- DTO 与端点形状一字未改（行号是内部排序键，不是对外字段）⇒ packages/api-contracts
-- 与 packages/sdk **不重新生成**，前端零改动。
-- ===========================================================================

-- ---------------------------------------------------------------------------
-- 1. 加列：NOT NULL + 临时默认值 0 ⇒ 加列这一步在非空表上也不会失败
-- ---------------------------------------------------------------------------
ALTER TABLE inventory_adjustment_order_line
  ADD COLUMN line_no integer NOT NULL DEFAULT 0;

-- ---------------------------------------------------------------------------
-- 2. 回填历史行：同一张单内按 id 排序给 1..n
-- ---------------------------------------------------------------------------
-- 历史行只有 id 可依（V260 时没有行号），而 id 是随机 UUID ⇒ 按 id 排序回填出来的
-- 序号**不还原当初的加行顺序**（那已经不可知），但它是**确定的、可复现的**，
-- 且从此以后行的顺序不再随 UUID 抖动 —— 这正是本次要钉死的那条性质。
UPDATE inventory_adjustment_order_line l
   SET line_no = t.rn
  FROM (SELECT id,
               row_number() OVER (PARTITION BY tenant_id, order_id ORDER BY id) AS rn
          FROM inventory_adjustment_order_line) t
 WHERE l.id = t.id;

-- ---------------------------------------------------------------------------
-- 3. 之后必须显式给行号：漏写就是 23502（响亮地炸），不留魔法默认值
-- ---------------------------------------------------------------------------
ALTER TABLE inventory_adjustment_order_line ALTER COLUMN line_no DROP DEFAULT;

-- ---------------------------------------------------------------------------
-- 4. 行号从 1 起；同一张单里唯一
-- ---------------------------------------------------------------------------
ALTER TABLE inventory_adjustment_order_line
  ADD CONSTRAINT inventory_adjustment_order_line_no_positive CHECK (line_no > 0);

ALTER TABLE inventory_adjustment_order_line
  ADD CONSTRAINT inventory_adjustment_order_line_order_no UNIQUE (tenant_id, order_id, line_no);

-- ---------------------------------------------------------------------------
-- 5. 旧的 (tenant_id, order_id) 索引被上面这个唯一索引的前缀**完全覆盖** ⇒ 去掉重复索引
-- ---------------------------------------------------------------------------
-- 两处读行（详情 / 过账预检）都是「tenant + order 定位、line_no 定序」，
-- 唯一索引 (tenant_id, order_id, line_no) 一样能服务 ⇒ 不留两个同前缀索引。
DROP INDEX inventory_adjustment_order_line_order;

-- ---------------------------------------------------------------------------
-- 6. 行号是单据的一部分：不允许事后改写
-- ---------------------------------------------------------------------------
-- 改行号 = 改写「操作员提交的顺序」⇒ 与数量、定位一样属于一次性快照的一部分。
CREATE OR REPLACE FUNCTION guard_inventory_adjustment_line_posted() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF OLD.posted_at IS NOT NULL THEN
    RAISE EXCEPTION '已过账的调整单行不可修改：它已经是库存分录的一部分，'
    '冲正必须写一张新单据，而不是改旧行。' USING ERRCODE='23514';
  END IF;
  -- 行与单据的绑定不可改：换了 order_id 等于把一行从一张单挪到另一张；
  -- 行号同理：重排行号就是重写单据的先后。
  IF (NEW.tenant_id,NEW.order_id,NEW.bucket_id,NEW.balance_id,NEW.legal_entity_id,NEW.sku_id,
      NEW.warehouse_id,NEW.location_id,NEW.lot_id,NEW.quality_status_id,
      NEW.qty_delta,NEW.reason_code,NEW.expected_version,NEW.created_at,NEW.line_no)
     IS DISTINCT FROM
     (OLD.tenant_id,OLD.order_id,OLD.bucket_id,OLD.balance_id,OLD.legal_entity_id,OLD.sku_id,
      OLD.warehouse_id,OLD.location_id,OLD.lot_id,OLD.quality_status_id,
      OLD.qty_delta,OLD.reason_code,OLD.expected_version,OLD.created_at,OLD.line_no) THEN
    RAISE EXCEPTION '调整单行的数量/定位/行号不可修改：行是一次性快照，'
    '改它等于让账与单据对不上' USING ERRCODE='23514';
  END IF;
  RETURN NEW;
END $$;
