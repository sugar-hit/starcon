-- ===========================================================================
-- 8.3.1.2 出库单详情（8.3 出库链路的串联视图）
-- ===========================================================================
-- 蓝图原文：「单出库单作业视图：明细行与已拣/已发量、关联销售订单与买家地址、预占引用、
-- 包裹列表、作业时间线。」输入：「outbound_order_id；关联对象。」输出：「详情 + 作业操作入口。」
-- 以及本模块被点名的那条关系：「**详情页串联整条出库链路**，作业人员不需要在多个页面跳。」
--
-- ---------------------------------------------------------------------------
-- 一、这个迁移是空的 —— 而且这是它应有的样子
-- ---------------------------------------------------------------------------
-- 调度器为 8.3.1.2 预分配了 V79。本迁移**刻意只建一张索引**，不建任何表，理由如下。
--
-- 8.3.1.1 已经在 V72 建好并拥有四张表：outbound_order（单头）、outbound_order_line
-- （明细计划快照）、outbound_pick_request（拣货交接请求）、outbound_order_event（作业留痕）。
-- 蓝图给 8.3.1.2 列的六段内容，逐段核对下来**全部落在那四张表里**：
--
--   蓝图段落              真实来源                                        状态
--   --------------------  ----------------------------------------------  ------------------
--   明细行                outbound_order_line（V72 §2）                   已有
--   作业时间线            outbound_order_event（V72 §4，append-only）      已有
--   已拣量                outbound_pick_request 快照 + event 留痕          部分，边界见第二节
--   已发量                outbound_order.status = SHIPPED                 部分，边界见第二节
--   关联销售订单/买家地址  只有 source_external_ref 字符串（9 未交付）      不可得，见第三节
--   预占引用              7.2.1 预占需求未交付，无 outbound 侧外键          不可得，见第三节
--   包裹列表              8.3.4.1 发货交接未交付                          不可得，见第三节
--
-- **所以本模块是纯读投影，不拥有任何事实表。** 这不是省事，而是边界纪律：预占引用归 7.2.1、
-- 包裹归 8.3.4.1、买家地址归 9 订单履约 —— 在这里建一张 outbound_reservation_ref 之类的表，
-- 就是给别人的事实表抢第二个写入所有者（AGENTS.md：「每张事实表只有一个写入所有者」）。
-- 上游交付后由它们自己的端点写入，本详情端点立即就能读到，无需迁移。
--
-- ---------------------------------------------------------------------------
-- 二、已拣量与已发量：本模块必须如实标注的边界
-- ---------------------------------------------------------------------------
-- 蓝图写的是「明细行与已拣/已发量」。这里必须说清楚每一段**到底有多少是真的**：
--
--   已拣量：**没有 picking_task 可查**。8.3.1.1 刻意不建那张表（归 8.3.2.1），
--     它只做到 outbound_pick_request 交接为止 —— 那是**请求量快照**，不是实拣量。
--     真实可给的最强信号有两个，都不是实拣量：
--       * outbound_pick_request 存在与否（一张单至多一条，V72 的 UNIQUE(tenant_id,order_id)）；
--       * outbound_order.status 是否已离开 PENDING_PICKING。
--     所以本模块**逐行返回已拣量 = NULL**（而不是 0，更不是猜一个百分比），
--     并在响应里给出 pickedQuantityAvailable=false + ownerModule=8.3.2.1 + 原因。
--     返回 0 会让作业员以为「一件都没拣」，那是**假数字**，比不显示更危险。
--
--   已发量：同理归 8.3.4.1。但**有一个真实信号可给**：outbound_order.status = SHIPPED
--     配 shipped_at。SHIPPED 是终态且 DB 层冻结（V72 §4.2），所以「已发量 = 计划件数」
--     在这张单上**是成立的**（明细计划快照不可改，V72 §4.4）。本模块只在 status=SHIPPED
--     时把已发量填成 total_piece_count，其余状态一律 NULL —— 绝不按「拣了多少推算了多少」。
--
-- ---------------------------------------------------------------------------
-- 三、四段拿不到的数据：不建占位表、不返回空集冒充成功
-- ---------------------------------------------------------------------------
--   关联销售订单与买家地址 —— 9 订单履约未交付。outbound_order 里只有
--     source_external_ref **字符串**，没有跨服务 FK（AGENTS.md 明令禁止），连表名都还没定。
--   预占引用 —— 7.2.1 预占需求列表未交付（台账「未开发」）。warehouse 服务里
--     inventory_transaction 有 kind='RESERVE' 这一类预占流水，但它的 ref_type 由
--     预占侧自己定、且当前没有任何 OUTBOUND_ORDER 引用形态，把 ref_type 猜成
--     'OUTBOUND_ORDER' 去 join 一张没人写的表，只是把「没数据」伪装成「查过了，确实没有」。
--   包裹列表 —— 8.3.4.1 发货交接未交付。print_target（V73，8.3.4.2 已交付）里有
--     carton_code / package_count，但它按 external_ref 字符串索引、不与出库单建 FK，
--     按出库单 id 反查同样是无根据的猜测。
--
-- 三段一律 available=false + ownerModule + href + 原因（照 8.2.1.1 的既有约定）。
--
-- ---------------------------------------------------------------------------
-- 四、为什么还有这一条 CREATE INDEX
-- ---------------------------------------------------------------------------
-- 详情端点每次调用都要按 (tenant_id, order_id) 读 outbound_order_event 的**全量时间线**，
-- 而 V72 建的那条索引是 (tenant_id, order_id, occurred_at, id) —— 前缀匹配对本查询够用，
-- 真正缺的是**按事件类型计数**（详情页要给出「建单 N 次 / 打印 M 次」这类可核对的口径）。
-- 这里补一条 (tenant_id, order_id, event_type) 部分索引，供该聚合一用。
--
-- **纯 CREATE INDEX，不 ALTER 任何既有表、不动任何既有列、不加任何 CHECK/SET NOT NULL/
-- 触发器** —— 因此对 8.3.1.1 及其它并行车道（8.3.2.1 / 8.3.3.x / 8.3.4.1 等引用同一批表）
-- **零回归面**：它们不需要重跑集成测试，行为与索引之前完全一致。
-- ===========================================================================

CREATE INDEX outbound_order_event_type
  ON outbound_order_event(tenant_id, order_id, event_type);