-- ===========================================================================
-- 一、为什么本模块需要一条迁移（而不是零迁移）
-- ===========================================================================
-- 本模块与 8.3.1.2 出库单详情、9.1.1.1 订单列表是同一形态的**纯读投影**：
-- 一行 INSERT / UPDATE / DELETE 都没有，不改 sales_order 簇任何一张表的结构，
-- 不建任何占位表。因此跨车道 DDL 回归面 = 0（既有的 9.1.2.2 / 9.1.1.1 /
-- 9.3.2.2 / 3.x trade 集成测试都不需要为本车道重跑）。
--
-- 但与前两个纯读投影不同的是：本模块要为 **warehouse 服务**（8.3.1.2 出库单详情）
-- 导出一个**授权 API**，让出库单详情页上那两块 available=false 的灰块能填上：
--   1. 关联销售订单
--   2. 买家地址
--
-- warehouse 出库单侧**早就记了**这一维：outbound_order.source_type='SALES' 时
-- source_external_ref 存的就是本服务 sales_order.order_no（V72 第 114 行原文：
-- 「外部单号：9 销售订单号」，且刻意是 varchar 而不是 uuid —— 跨服务不猜对方 id 形态，
-- 更重要的是它让「一个订单多张出库单」（分仓/分批）在数据上成立）。
--
-- 也就是说 warehouse 手上**已经有这个键**，缺的只是拿它查回订单的能力。
-- 而按来源需求反查订单号，当前只有 UNIQUE(tenant_id, order_no) 这条**唯一约束**索引：
--   * 它能定位单张单，但 UNIQUE 索引是**先按 tenant_id 定位再比对 order_no**，
--     对「一批出库单批量反查它们的销售订单」这种批量调用不友好；
--   * 订单号形如 MO-20261011-3f2a1c9b，**不是 uuid 前缀**，无法走任何 uuid 侧的索引。
--
-- 本条索引**只为这一条查询存在**：
--   * 前导 tenant_id —— 与本服务所有业务索引同一纪律（RLS 谓词在租户列上，
--     前导列不是 tenant_id 会让 RLS 下的每租户扫描都退化成全表）；
--   * 第二列 order_source —— 与 sales_order_external_no_unique（V99 第 539 行）
--     同一纪律：同一串号码在 MANUAL 与将来的 PLATFORM 下是两件不相干的事，
--     只按 (tenant_id, order_no) 反查会把不同来源的同号订单混进一次响应。
--   * 覆盖列 order_no —— 本查询只需要 order_no，可走 **index-only scan**。
--
-- ===========================================================================
-- 二、本迁移**刻意没有**建的三张表（重要：不要在本车道补建）
-- ===========================================================================
-- 蓝图与实体目录 db/schemas/v2/README.md（第 106 / 107 行）点名了两张表：
--
--   | order_charge_allocation | 费用到行的分摊；分摊之和等于头金额，保留舍入差额 |
--   | order_line_component    | 售出一行展开的组件与数量，历史快照                    |
--
-- **V99__trade_manual_sales_order.sql 实际只建了七张表，没有这两张。**
-- 逐一核对 V99 的 CREATE TABLE：sales_order / sales_order_party_snapshot /
-- sales_order_line / order_line_attribute_snapshot / order_address_snapshot /
-- order_charge / sales_order_status_history —— 确认二者均不存在。
--
-- 处置纪律（照 8.3.1.2 / 9.1.1.1 已建立的仓库约定）：
--
--   * **费用分摊** → 报 available=false，ownerModule = 9.1.2.2。
--     V99 第 320-323 行原文已经写明立场：「这里**不是**行级分摊明细……
--     真要做行级分摊时另开 order_charge_allocation 子表，**别拿 charge_kind
--     当分摊记号**」。charge_kind 只有 ORDER / LINE 两值，是「这笔费用挂在整单
--     还是记在某行名下」的**归属**，不是「金额按什么比例摊到各行」的**分摊明细**。
--     拿 charge_type 的合计冒充分摊，等于回答了一个没人问的问题、
--     却让真正的问题（这一行到底买了多少钱）保持沉默。
--     **创建该子表的写入所有权属于 9.1.2.2**，本模块是读投影，不抢写。
--
--   * **组件展开** → 报 available=false，ownerModule = **9.1.2.2**（点名）。
--     订单行展开成组件是**建单时算出来的快照**：bundle 在建单那一刻被展开，
--     展开结果就是这张订单行的历史凭据。展开需要 BOM 解析与 SKU 映射版本，
--     那是**写入侧**的职责，读侧凭空造不出真数据（更不该造）。
--     catalog 侧 V24 / BundleComponentService 只提到 order_line_component 是
--     「下游 09 订单的消费者」，**catalog 自己也没有这张表** —— 它是订单服务
--     该建而未建的表，属 9.1.2.2 的交付缺口，本车道点名上报，不代建。
--
--   * 支付与退款（12 财务未交付）、履约批次与包裹（9.3.3.1 / 8.3.4.1 未交付）、
--     物流轨迹（10 未交付）、售后关联（11 一条未做）、
--     平台侧原始报文（9.1.2.1 未交付）—— 同样一律 available=false。
--     **绝不为它们建占位表**：一张恒空的表会让「这段能力还没接入」
--     被读成「这段能力查过了，确实没有数据」。
--
