-- 9.1.1.1 订单列表（全渠道统一订单列表的读投影）。
--
-- 蓝图 09-order-and-fulfillment.md 9.1.1.1 原文：
--   职责：全渠道订单统一列表：订单号、平台店铺、下单时间、买家、SKU 行数、总金额/币种、
--         支付状态、履约状态、发货仓、平台状态，支持多维筛选、导出与批量操作
--         （审单、备注、取消、发催付）。
--   输入：筛选条件（平台、店铺、时间、状态、金额、买家、SKU、发货仓）；用户数据范围。
--   输出：分页列表 + 汇总条（订单数/金额/待处理数）；批量操作结果。
--
-- ===========================================================================
-- 第零节：**本模块是读投影，不是写入者** —— 本迁移只建两条索引
-- ===========================================================================
-- 上一条车道（9.1.2.2 手工订单，V99）建好了 sales_order / sales_order_line /
-- sales_order_party_snapshot / order_address_snapshot / order_charge /
-- order_line_attribute_snapshot / sales_order_status_history 七张表。
-- **sales_order 的写入所有权属于 9.1.2.2（手工单）与将来的 9.1.2.1（平台单同步）**，
-- 本模块是它们交付后的**第一个读方**。因此本迁移：
--
--   * **零新建表** —— 蓝图要的每一个展示维度要么落在 V99 的既有列上，要么根本不存在。
--     为不存在的维度建占位表，会让「平台状态 = NULL」被读成「平台还没回传状态」，
--     而不是「平台同步这个模块还没交付」。空集冒充成功正是 8.3.1.2 立规矩要禁掉的东西。
--   * **零 ALTER 既有表** —— 不加列、不加 CHECK、不加 SET NOT NULL、不加触发器。
--     所以**跨车道 DDL 回归面 = 0**：V1 的 trade_tenancy_probe、V92 的七张
--     fulfillment_*、V97 的五张加工单表、V98 的两张 BOM 快照表、
--     以及 V99 的七张表，既有的约束与触发器一字未动，
--     既有四个 trade 模块的集成测试不需要为本车道重跑。
--   * **只加两条 CREATE INDEX**（第三节）—— 这不是 DDL 约束，不拒绝任何一行写入，
--     只是让本模块的真实查询形状能走上索引。与 8.3.1.2 出库单详情
--     「只建一条索引、零新建表、零 ALTER」的纯读投影先例同一形态。
--
-- 版本号 V100 按**服务内**独立递增（catalog/identity/warehouse/crm 各有自己的 V1 与
-- V30+；V77 同时出现在 identity 与 warehouse）。trade 现有 V1/V92/V97/V98/V99，
-- V100 是下一个空位。catalog 那边也有个 V100，但那是**另一个数据库**的 Flyway 历史，
-- 与本文件无关；只有**同一服务内**两条迁移撞号才是事故。

-- ===========================================================================
-- 一、本模块读到的**真实维度**（全部落在 V99 的既有列上）
-- ===========================================================================
--   订单号     sales_order.order_no                （V99 已有 UNIQUE(tenant_id,order_no)）
--   下单时间   sales_order.created_at / submitted_at
--   金额/币种  sales_order.grand_total_amount numeric(19,4) + currency char(3)
--   来源       sales_order.order_source            （CHECK 已含 MANUAL 与全部平台来源）
--   单据状态   sales_order.status                   （CHECK 只有 DRAFT / SUBMITTED）
--   买家       sales_order_party_snapshot.customer_name / customer_party_id
--   SKU 行数   sales_order_line 聚合
--   SKU 筛选   sales_order_line.sku_id
--
-- ===========================================================================
-- 二、蓝图要的、**本模块拿不到**的维度（本迁移一个字都不碰）
-- ===========================================================================
-- 这些在**服务层**按 8.3.1.2 立的规矩显式报 available=false（每条带 ownerModule 与原因），
-- 列表响应里对应字段为 **null 而不是 0 或假枚举**。理由逐条钉死：
--
--   平台店铺   sales_order **没有店铺列**。2 平台同步 / 2.x 店铺归属未交付；
--              手工单本就无平台店铺。→ ownerModule 2 平台同步
--   支付状态   sales_order 只有 **payment_method（付款方式）**，没有支付状态。
--              付款方式是我方与客户的**约定**（预付/货到付/电汇/账期），
--              支付状态是**实收流水**（已付/部分付/未付/逾期）。两者语义相反，
--              拿 payment_method 冒充 paymentStatus 是语义造假。→ ownerModule 12 财务
--   履约状态   status 的 CHECK **只有 ('DRAFT','SUBMITTED')**，是「这张单有没有进审单队列」，
--              **完全没有履约概念**（未拣货/已拣货/已发货/已签收）。把它标成履约状态
--              会让「已发货」的单在界面上显示成「已提交待审」。→ ownerModule 9.3 履约
--   发货仓     8.3 出库侧存在，但**销售订单与出库单之间尚无履约请求关联**
--              （9.3.3.1 未交付），订单上没有任何列指向发货仓。→ ownerModule 9.3.3.1
--   平台状态   平台同步未交付，没有任何平台回传状态落库。→ ownerModule 9.1.2.1
--   售后状态   11 售后一条未做，sales_order 簇里没有任何售后列。→ ownerModule 11 售后
--
-- 「列表状态是多状态的组合展示（支付 × 履约 × 售后）」这三个维度**一个都不存在**，
-- 所以本模块**不提供**这三个维度的筛选与排序参数 ——
-- 提供一个永远筛不出东西、也永远排不出顺序的参数，比不提供更糟：
-- 界面上的下拉框会让人以为这条链路已经通了。

-- ===========================================================================
-- 三、两条索引（按本模块真实的查询形状建，不多建）
-- ===========================================================================
--
-- 3.1 **按金额排序 / 按金额区间筛选**（蓝图输入句的「金额」维度）。
--     V99 已有的 sales_order_by_source 是 (tenant_id, order_source, status, created_at, id)，
--     金额**不在里面**，而本模块支持按 grand_total_amount 排序与金额区间筛选，
--     且金额在同一个租户内可能跨币种（currency 各自独立），排序必然要扫全租户的行。
--     这是**本模块排序维度里唯一没有索引可用**的一个，补在这里。
CREATE INDEX sales_order_by_amount
  ON sales_order(tenant_id, grand_total_amount, id);

-- 3.2 **按 SKU 筛选订单**（蓝图输入句的「SKU」维度）。
--     sales_order_line 现有的索引是 (tenant_id, order_id, line_no)，lead 列是 order_id，
--     「这个 SKU 出现在哪些订单里」是**反向**查询，走不上那条索引
--     —— 列表页每翻一页都要全表扫订单行。
CREATE INDEX sales_order_line_by_sku
  ON sales_order_line(tenant_id, sku_id, order_id);

-- ===========================================================================
-- 四、刻意**不建**的索引
-- ===========================================================================
--   * sales_order(tenant_id, customer_name)：customer_name 在客户快照表上，
--     已有 sales_order_party_by_customer (tenant_id, customer_party_id, created_at, id)
--     服务按客户反查；买家名模糊检索刻意走 ILIKE，不为它建索引 ——
--     前导通配的 LIKE 本来就用不上 B-tree 索引，建了只是白占写入成本。
--   * sales_order(tenant_id, currency)：币种是低基数筛选条件，
--     走 sales_order_by_amount 的 tenant_id 前缀即可，全租户扫描已经是 O(命中行数)。
--   * sales_order(tenant_id, created_at, id)：本模块的默认排序是 created_at desc，
--     V99 的 sales_order_by_source 前缀不同，但两者代价相同且前者已在本服务存在，
--     **刻意不重复建** —— 多车道共用的库，每条索引都是所有写入者的成本。
