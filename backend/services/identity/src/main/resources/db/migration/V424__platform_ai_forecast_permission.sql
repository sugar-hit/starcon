-- V424 · platform_ai_forecast_permission —— 18.4.2.2「选品与需求预测」的权限码登记
-- ===========================================================================
--
-- 蓝图 18「集成开放与智能自动化」→ 18.4「AI 与智能」→ 18.4.2「AI 业务能力」
-- → 18.4.2.2「选品与需求预测」。
--
-- ⚠️ **平台侧迁移与本迁移成对**（同一个版本号 V424）：
--   backend/services/platform/src/main/resources/db/migration/V424__ai_forecast.sql
--   建表；本迁移登记权限码。两者必须**一起**上线 ——
--   表建好而权限码没登记 ⇒ 端点在真实环境里恒 403（权限码要有角色持有才生效）。
--
-- ---------------------------------------------------------------------------
-- 一、登记哪几个码
-- ---------------------------------------------------------------------------
--
--   platform.ai_forecast.read    读预测结果 / 区间 / 影响因素 / 建议 / 爆品 / 机会品 /
--                                促销日历 / 需求历史 / 运行记录 / 能力声明
--   platform.ai_forecast.create  登记促销、录入需求历史、同步上游销量、发起一次预测运行
--   platform.ai_forecast.update  删除促销 / 删除需求历史录入
--   platform.ai_forecast.adopt   人工采纳 / 驳回建议（**决策动作**）
--
-- 🔴 **「采纳建议」独立成一个码**，不并进 update：
--   蓝图加粗句「**建议只作为参考输入，不自动执行**」说的是一道**门槛** ——
--   能改预测参数的人不该顺手把别人的建议标成「已采纳」。
--   「采纳」只是**记录人的决定**，本模块**不执行**任何下游动作
--   （补货单归 6 采购，调价归 5 定价）。
--
-- 刻意**只**登记这 4 个动作：没有端点的权限码不注册
-- （与 identity V104 / V53 / V330 / V378 / V380 同一纪律）。
--
-- ---------------------------------------------------------------------------
-- 二、为什么 page_code 取 platform.ai_forecast
-- ---------------------------------------------------------------------------
--
-- permission.page_code 有外键指向 page_resource(code)，所以必须先插页面行。
-- page_resource 对应**菜单入口**，不是动作。
-- 「选品与需求预测」是 18.4.2.2 的**同一个页面**
-- （预测结果 + 建议 + 促销日历 + 需求历史在同一处管理），
-- 不是四个页面 —— 拆成四个会在菜单里多出三个与「选品与需求预测」重复的条目。
--
-- 前缀取 platform.ai_forecast：本模块的权限码由 **platform 服务**消费
-- （platform.ai_forecast.read），与 catalog.spu / warehouse.facilities / platform.text
-- 的「服务名.页面」口径一致；权限码跟着**消费它的服务**走，
-- 才能在审计时回答「谁被授权改这一类东西」。
--
-- ---------------------------------------------------------------------------
-- 三、为什么必须给存量 OWNER 补权
-- ---------------------------------------------------------------------------
--
-- 新建子租户由 create_child（V47）把 permission 表里的**全部**权限码授给 OWNER，
-- 所以新租户自动就有这 4 个码 —— 但**存量租户**的 OWNER 角色是在这 4 个码登记之前建的，
-- 不会自动获得它们 ⇒ 迁移上线后这些租户会突然「什么都点不动」。
--
-- 用 LIKE 'platform.ai_forecast.%' 扫**整个集合**，而不是只补 read 一条：
--   覆盖本迁移登记的全部动作，且**幂等**（ON CONFLICT DO NOTHING）。
--
-- 与 V3 / V8 / V104 / V330 / V378 / V380 同口径：租户所有者始终拥有全部页面权限。
--
-- ⚠️ **不碰其它前缀**：platform.text.%（18.4.2.1，V380）、platform.automation_rule%（18.3.x）
--   等由各自的迁移登记 —— 本迁移**只**动 platform.ai_forecast.%。

-- ---------------------------------------------------------------------------
-- 1. 页面资源（菜单入口）
-- ---------------------------------------------------------------------------
INSERT INTO page_resource(code,name) VALUES ('platform.ai_forecast','选品与需求预测')
ON CONFLICT (code) DO NOTHING;

-- ---------------------------------------------------------------------------
-- 2. 权限码（4 个动作）
-- ---------------------------------------------------------------------------
INSERT INTO permission SELECT 'platform.ai_forecast.'||action,'platform.ai_forecast',action
FROM unnest(ARRAY['read','create','update','adopt']::text[]) action
ON CONFLICT (code) DO NOTHING;

-- ---------------------------------------------------------------------------
-- 3. 存量 OWNER 补权（覆盖 platform.ai_forecast.% 整个集合）
-- ---------------------------------------------------------------------------
INSERT INTO role_permission SELECT r.tenant_id,r.id,p.code FROM role r CROSS JOIN permission p
 WHERE r.code='OWNER' AND p.code LIKE 'platform.ai_forecast.%' ON CONFLICT DO NOTHING;
