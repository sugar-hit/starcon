-- ===========================================================================
-- V382 · platform_finance_permission —— 18.2.1.1「财务软件」的 platform.finance 权限码登记
-- ===========================================================================
--
-- 蓝图 18「集成开放与智能自动化」→ 18.2「财务与资金」→ 18.2.1「财务软件」→ 18.2.1.1「财务软件」。
--
-- ---------------------------------------------------------------------------
-- 一、为什么需要这个迁移（补的是既有缺口，不是本车道扩大范围）
-- ---------------------------------------------------------------------------
--
-- platform 服务的 FinanceSoftwareController 用
--     access.require(bearer, "platform.finance." + permission)
-- 强制鉴权，端点实际用到 6 个动作：read / create / update / export / reconcile / push。
--
-- 但 identity 服务的 permission 表里**从来没有注册过 platform.finance 任何一行** ——
-- 而 role_permission.permission_code 有指向 permission(code) 的外键 ——
-- 于是「没有任何角色可能持有 platform.finance.read」，
-- 这些端点在真实环境里恒 403。
--
-- （与 V378 登记 platform.app.*、V380 登记 platform.text.* 的缺口**完全同构**：
--   那两批同样是「服务已交付、权限码没登记」。）
--
-- 本迁移只做一件事：把这 6 个码登记进 identity 的权限码表。
--
-- ---------------------------------------------------------------------------
-- 二、登记哪几个码
-- ---------------------------------------------------------------------------
--
--   platform.finance.read      读连接档案 / 科目映射 / 主数据映射 / 凭证文件记录 /
--                              核对任务 / 外部余额 / 差异 / 能力声明
--   platform.finance.create    登记连接、科目映射、主数据映射、核对任务、导入外部余额
--   platform.finance.update    改连接与映射、停用连接、重算核对
--   platform.finance.export    **导出凭证文件**（文件要离开本系统，单独授权）
--   platform.finance.reconcile **算余额核对差异**（对账是独立职责，单独授权）
--   platform.finance.push      **直连推送凭证到外部财务软件**
--
-- 刻意**只**登记这 6 个动作：没有端点的权限码不注册
-- （与 identity V104 / V53 / V330 / V378 / V380 同一纪律）。
--
-- 「导出」与「推送」是**两个独立的码**：导出是**文件**（人拿走去导入，文件出本系统），
-- 推送是**直连**（本系统自己调对方的接口）。两者影响面不同 ——
-- 能导出不代表能把文件直连塞进法定账。
--
-- 「核对」也独立成一个码：算差异是财务的独立职责，
-- 不该让「能配科目映射的人」顺手把对账结论也定了。
--
-- ⚠️ platform.finance.push 目前**恒 409**（外部财务软件适配器未接入，
--   见 V382__finance_software.sql 第 0 节）—— 但权限码**照样登记**：
--   端点要在权限校验**之后**如实答「未接入」，而不是先被 403 挡掉。
--   先答 403 会让运营以为「有权限就能推」，从而去找「是不是少了权限」。
--
-- ---------------------------------------------------------------------------
-- 三、为什么 page_code 取 platform.finance
-- ---------------------------------------------------------------------------
--
-- permission.page_code 有外键指向 page_resource(code)，所以必须先插页面行。
--
-- page_resource 对应**菜单入口**，不是动作。
-- 「财务软件」是 18.2.1.1 的**同一个页面**（连接档案 / 科目映射 / 主数据映射 /
-- 凭证文件 / 余额核对在同一处管理），不是六个页面。
--
-- 前缀取 platform.finance 而不是 finance.software：本模块的权限码由
-- **platform 服务**消费（platform.finance.read），与 catalog.spu / warehouse.facilities /
-- platform.app / platform.text 的「服务名.页面」口径一致；
-- 权限码跟着**消费它的服务**走，才能在审计时回答「谁被授权改这一类东西」。
--
-- ⚠️ **不碰 finance.* 与 platform.app.* / platform.text.***：
--   finance.* 是 12 财务核算服务自己的权限码，platform.app.* 是 18.1.1.1、
--   platform.text.* 是 18.4.2.1 —— 本迁移**只**动 platform.finance.%，
--   三个批次的权限码互不覆盖。
--
-- ---------------------------------------------------------------------------
-- 四、为什么必须给存量 OWNER 补权（这是本迁移最容易漏的一步）
-- ---------------------------------------------------------------------------
--
-- 新建子租户由 create_child（V47）把 permission 表里的**全部**权限码授给 OWNER，
-- 所以新租户自动就有这 6 个码 —— 但**存量租户**的 OWNER 角色是在这 6 个码登记之前建的，
-- 不会自动获得它们 ⇒ 迁移上线后这些租户会突然「什么都点不动」。
--
-- 用 LIKE 'platform.finance.%' 扫**整个集合**，而不是只补 read 一条：
--   · 覆盖本迁移登记的全部 6 个动作；
--   · 幂等 —— 重复执行不产生重复行（ON CONFLICT DO NOTHING）。
--
-- 与 V3 / V8 / V104 / V330 / V378 / V380 同口径：租户所有者始终拥有全部页面权限。
--
-- ---------------------------------------------------------------------------
-- 五、幂等
-- ---------------------------------------------------------------------------
--
-- 三段式全部带 ON CONFLICT DO NOTHING：同一段 SQL 跑两次不报错、不产生重复行。
-- ===========================================================================

-- ---------------------------------------------------------------------------
-- 1. 页面资源（菜单入口）
-- ---------------------------------------------------------------------------
INSERT INTO page_resource(code,name) VALUES ('platform.finance','财务软件')
ON CONFLICT (code) DO NOTHING;

-- ---------------------------------------------------------------------------
-- 2. 权限码（6 个动作）
-- ---------------------------------------------------------------------------
INSERT INTO permission SELECT 'platform.finance.'||action,'platform.finance',action
FROM unnest(ARRAY['read','create','update','export','reconcile','push']::text[]) action
ON CONFLICT (code) DO NOTHING;

-- ---------------------------------------------------------------------------
-- 3. 存量 OWNER 补权（覆盖 platform.finance.% 整个集合）
-- ---------------------------------------------------------------------------
INSERT INTO role_permission SELECT r.tenant_id,r.id,p.code FROM role r CROSS JOIN permission p
 WHERE r.code='OWNER' AND p.code LIKE 'platform.finance.%' ON CONFLICT DO NOTHING;
