-- ===========================================================================
-- V418 · platform_external_permission —— 18.2.3.1「其他对接」的 platform.external 权限码登记
-- ===========================================================================
--
-- 蓝图 18「集成开放与智能自动化」→ 18.2「外部系统对接」→ 18.2.3「其他对接」→ 18.2.3.1。
--
-- ---------------------------------------------------------------------------
-- 一、为什么需要这个迁移
-- ---------------------------------------------------------------------------
--
-- platform 服务的 ExternalIntegrationController 用
--     access.require(bearer, "platform.external." + permission)
-- 强制鉴权，端点实际用到 4 个动作：read / create / update / sync。
--
-- 但 identity 服务的 permission 表里**从来没有注册过 platform.external 任何一行** ——
-- 而 role_permission.permission_code 有指向 permission(code) 的外键 ——
-- 于是「没有任何角色可能持有 platform.external.read」，
-- 这些端点在真实环境里恒 403。
--
-- （与 V378 登记 platform.app.*、V380 登记 platform.text.*、V382 登记 platform.finance.*、
--   V411–V415 登记 platform.api.* / platform.webhook.* / platform.delivery.* /
--   platform.call.* / platform.io.* 的缺口**完全同构**：那几批同样是「服务已交付、权限码没登记」。）
--
-- 本迁移只做一件事：把这 4 个码登记进 identity 的权限码表。
--
-- ---------------------------------------------------------------------------
-- 二、登记哪几个码
-- ---------------------------------------------------------------------------
--
--   platform.external.read   读连接配置 / 同步任务 / 同步记录 / 健康状态 / 能力声明 / 上游渠道
--   platform.external.create 登记连接配置、登记同步任务配置、登记外部侧已完成的同步记录
--   platform.external.update 改连接配置、停用连接、停用同步任务、重算某个连接的健康状态
--   platform.external.sync   **经由外部通道发起一次同步**（对外发请求）
--
-- 刻意**只**登记这 4 个动作：没有端点的权限码不注册
-- （与 identity V104 / V53 / V330 / V378 / V380 / V382 同一纪律）。
--
-- 「配置」与「同步」是**两个独立的码**，理由与 18.2.1.1 的「导出 / 推送」、
-- 18.2.2.1 的「执行 / 同步」同源：
--   · 「配置」= 在本系统里登记一条连接 / 一个同步任务（**只动本系统的账**）。
--   · 「同步」= **对外发请求**。哪怕当前外部通道未接入（恒 409），
--     这个码也**照样登记**：端点要在权限校验**之后**如实答「未接入」，
--     而不是先被 403 挡掉 —— 先答 403 会让运营以为「有权限就能同步」，
--     从而去找「是不是少了权限」。
--
-- ---------------------------------------------------------------------------
-- 三、为什么 page_code 取 platform.external
-- ---------------------------------------------------------------------------
--
-- permission.page_code 有外键指向 page_resource(code)，所以必须先插页面行。
--
-- page_resource 对应**菜单入口**，不是动作。
-- 「其他对接」是 18.2.3.1 的**同一个页面**
-- （连接配置 / 同步任务 / 同步记录 / 健康状态在同一处管理），不是一个动作一个页面。
--
-- 前缀取 platform.external 而不是 channel.external / trade.external：
-- 本模块的权限码由 **platform 服务**消费（platform.external.read），
-- 与 catalog.spu / warehouse.facilities / platform.app / platform.text /
-- platform.finance / platform.payment 的「服务名.页面」口径一致；
-- 权限码跟着**消费它的服务**走，才能在审计时回答「谁被授权动外部对接」。
--
-- ⚠️ **不碰 channel.* 与 platform.* 的既有前缀**：
--   channel.* 是 02 渠道与店铺服务自己的权限码，
--   platform.app / platform.text / platform.finance / platform.payment /
--   platform.api / platform.webhook / platform.delivery / platform.call / platform.io
--   分别是 18.1.1.1 / 18.4.2.1 / 18.2.1.1 / 18.2.2.1 / 18.1.1.2 / 18.1.2.1 /
--   18.1.2.2 / 18.1.4.1 / 18.1.3.1 的权限码 ——
--   本迁移**只**动 platform.external.%，几批的权限码互不覆盖。
--
-- ---------------------------------------------------------------------------
-- 四、为什么必须给存量 OWNER 补权（这是本迁移最容易漏的一步）
-- ---------------------------------------------------------------------------
--
-- 新建子租户由 create_child（V47）把 permission 表里的**全部**权限码授给 OWNER，
-- 所以新租户自动就有这 4 个码 —— 但**存量租户**的 OWNER 角色是在这 4 个码登记之前建的，
-- 不会自动获得它们 ⇒ 迁移上线后这些租户会突然「什么都点不动」。
--
-- 用 LIKE 'platform.external.%' 扫**整个集合**，而不是只补 read 一条：
--   · 覆盖本迁移登记的全部 4 个动作；
--   · 幂等 —— 重复执行不产生重复行（ON CONFLICT DO NOTHING）。
--
-- 与 V3 / V8 / V104 / V330 / V378 / V380 / V382 同口径：租户所有者始终拥有全部页面权限。
--
-- ---------------------------------------------------------------------------
-- 五、幂等
-- ---------------------------------------------------------------------------
--
-- 三段式全部带 ON CONFLICT DO NOTHING：同一段 SQL 跑两次不报错、不产生重复行。
-- ===========================================================================

-- ---------------------------------------------------------------------------
-- 1. 页面资源（菜单入口）
-- ---------------------------------------------------------------------------
INSERT INTO page_resource(code,name) VALUES ('platform.external','其他对接')
ON CONFLICT (code) DO NOTHING;

-- ---------------------------------------------------------------------------
-- 2. 权限码（4 个动作）
-- ---------------------------------------------------------------------------
INSERT INTO permission SELECT 'platform.external.'||action,'platform.external',action
FROM unnest(ARRAY['read','create','update','sync']::text[]) action
ON CONFLICT (code) DO NOTHING;

-- ---------------------------------------------------------------------------
-- 3. 存量 OWNER 补权（覆盖 platform.external.% 整个集合）
-- ---------------------------------------------------------------------------
INSERT INTO role_permission SELECT r.tenant_id,r.id,p.code FROM role r CROSS JOIN permission p
 WHERE r.code='OWNER' AND p.code LIKE 'platform.external.%' ON CONFLICT DO NOTHING;
