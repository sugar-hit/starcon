-- V429 · platform_ai_diagnosis_permission —— 18.4.2.3「异常诊断」的权限码登记
-- ===========================================================================
--
-- 蓝图 18「集成开放与智能自动化」→ 18.4「AI 能力」→ 18.4.2「AI 业务能力」
-- → 18.4.2.3「异常诊断」。
--
-- ⚠️ **平台侧迁移与本迁移成对**（同一个版本号 V429）：
--   backend/services/platform/src/main/resources/db/migration/V429__ai_diagnosis.sql
--   建表；本迁移登记权限码。两者必须**一起**上线 ——
--   表建好而权限码没登记 ⇒ 端点在真实环境里恒 403（权限码要有角色持有才生效）。
--
-- ---------------------------------------------------------------------------
-- 一、登记哪几个码
-- ---------------------------------------------------------------------------
--
--   platform.ai_diagnosis.read    读异常事件列表 / 事件详情 / 诊断结论 / 依据事实 /
--                                归因规则口径 / 能力声明 / 概览
--   platform.ai_diagnosis.create  提交异常事件、发起一次诊断、从平台内部失败源同步事件
--   platform.ai_diagnosis.update  人工标记异常事件已处置（写处置说明）
--
-- 🔴 **「标记已处置」独立成一个码**，不并进 create：
--   诊断（create）会**新增**结论与依据；标记已处置（update）会**改**既有事件的状态。
--   两者的审计含义不同 —— 「谁在什么事件上写了处置结论」与「谁关掉了这个事件」
--   需要能分开回答。
--
-- 刻意**只**登记这 3 个动作：没有端点的权限码不注册
-- （与 identity V104 / V53 / V330 / V378 / V380 / V424 同纪律）。
--
-- ---------------------------------------------------------------------------
-- 二、为什么 page_code 取 platform.ai_diagnosis
-- ---------------------------------------------------------------------------
--
-- permission.page_code 有外键指向 page_resource(code)，所以必须先插页面行。
-- page_resource 对应**菜单入口**，不是动作。
-- 「异常诊断」是 18.4.2.3 的**同一个页面**（异常事件列表 + 诊断详情 + 依据事实 +
-- 处置建议 + 能力声明在同一处管理），不是三个页面 ——
-- 拆成三个会在菜单里多出两个与「异常诊断」重复的条目。
--
-- 前缀取 platform.ai_diagnosis：本模块的权限码由 **platform 服务**消费
-- （platform.ai_diagnosis.read），与 catalog.spu / warehouse.facilities / platform.text /
-- platform.ai_forecast 的「服务名.页面」口径一致；权限码跟着**消费它的服务**走，
-- 才能在审计时回答「谁被授权改这一类东西」。
--
-- ---------------------------------------------------------------------------
-- 三、为什么必须给存量 OWNER 补权
-- ---------------------------------------------------------------------------
--
-- 新建子租户由 create_child（V47）把 permission 表里的**全部**权限码授给 OWNER，
-- 所以新租户自动就有这 3 个码 —— 但**存量租户**的 OWNER 角色是在这 3 个码登记之前建的，
-- 不会自动获得它们 ⇒ 迁移上线后这些租户会突然「什么都点不动」。
--
-- 用 LIKE 'platform.ai_diagnosis.%' 扫**整个集合**，而不是只补 read 一条：
--   覆盖本迁移登记的全部动作，且**幂等**（ON CONFLICT DO NOTHING）。
--
-- 与 V3 / V8 / V104 / V330 / V378 / V380 / V424 同口径：租户所有者始终拥有全部页面权限。
--
-- ⚠️ **不碰其它前缀**：platform.text.%（18.4.2.1，V380）、platform.ai_forecast.%（18.4.2.2，V424）、
--   platform.ai_usage.%（18.4.3.1）、platform.ai_templates.%（18.5.1.1）、
--   platform.automation_rule%（18.3.x）等由各自的迁移登记 ——
--   本迁移**只**动 platform.ai_diagnosis.%。

-- ---------------------------------------------------------------------------
-- 1. 页面资源（菜单入口）
-- ---------------------------------------------------------------------------
INSERT INTO page_resource(code,name) VALUES ('platform.ai_diagnosis','异常诊断')
ON CONFLICT (code) DO NOTHING;

-- ---------------------------------------------------------------------------
-- 2. 权限码（3 个动作）
-- ---------------------------------------------------------------------------
INSERT INTO permission SELECT 'platform.ai_diagnosis.'||action,'platform.ai_diagnosis',action
FROM unnest(ARRAY['read','create','update']::text[]) action
ON CONFLICT (code) DO NOTHING;

-- ---------------------------------------------------------------------------
-- 3. 存量 OWNER 补权（覆盖 platform.ai_diagnosis.% 整个集合）
-- ---------------------------------------------------------------------------
INSERT INTO role_permission SELECT r.tenant_id,r.id,p.code FROM role r CROSS JOIN permission p
 WHERE r.code='OWNER' AND p.code LIKE 'platform.ai_diagnosis.%' ON CONFLICT DO NOTHING;
