-- ===========================================================================
-- 18.1.2.1 事件订阅：platform.webhook 权限码登记
-- ===========================================================================
--
-- 蓝图 18「集成开放与智能自动化」→ 18.1「应用与凭证」→ 18.1.2「事件订阅」→ 18.1.2.1「事件订阅」。
--
-- ---------------------------------------------------------------------------
-- 一、为什么需要这个迁移
-- ---------------------------------------------------------------------------
--
-- platform 服务的 EventSubscriptionController 用
--     access.require(bearer, "platform.webhook." + permission)
-- 强制鉴权，端点实际只用到 4 个动作：read / create / update / revoke。
--
-- identity 服务的 permission 表里**从来没有注册过 platform.webhook 任何一行** ——
-- 而 role_permission.permission_code 有指向 permission(code) 的外键 ——
-- 于是「没有任何角色可能持有 platform.webhook.read」，
-- 这些端点在真实环境里恒 403。
--
-- 本迁移只做一件事：把这 4 个码登记进 identity 的权限码表。
--
-- ---------------------------------------------------------------------------
-- 二、登记哪几个码
-- ---------------------------------------------------------------------------
--
--   platform.webhook.read    读事件定义列表 / 订阅列表与详情 / 策略 / 审计事件
--   platform.webhook.create  登记事件定义、创建订阅
--   platform.webhook.update  改订阅、改事件过滤、生成/轮换签名密钥、配重试与死信策略
--   platform.webhook.revoke  吊销订阅与吊销签名密钥
--
-- 刻意**只**登记这 4 个动作：没有端点的权限码不注册
-- （与 identity V104 / V53 / V330 / V378 同一纪律）。
--
-- 吊销是**独立**的一个码而不是 update：能改订阅的人不该顺手把别人的订阅掐了。
--
-- ⚠️ 与 V378 的 `platform.app.*` **刻意不共用前缀**：
--   「应用与凭证」（18.1.1.1）与「事件订阅」（18.1.2.1）是两个页面、两组权限。
--
-- ---------------------------------------------------------------------------
-- 三、为什么 page_code 取 platform.webhook
-- ---------------------------------------------------------------------------
--
-- permission.page_code 有外键指向 page_resource(code)，所以必须先插页面行。
--
-- page_resource 对应**菜单入口**，不是动作。
-- 「事件订阅」是 18.1.2 的**同一个页面**（事件定义 / 订阅 / 策略在同一处管理），
-- 不是四个页面 —— 拆成四个 page_resource 会在菜单里多出三个重复条目。
--
-- 前缀取 platform.webhook 而不是 identity.webhook：本模块的权限码由 **platform 服务**消费
-- （platform.webhook.read），与 catalog.spu / warehouse.facilities 的「服务名.页面」口径一致。
--
-- ---------------------------------------------------------------------------
-- 四、为什么必须给存量 OWNER 补权（这是本迁移最容易漏的一步）
-- ---------------------------------------------------------------------------
--
-- 新建子租户由 create_child（V47）把 permission 表里的**全部**权限码授给 OWNER，
-- 所以新租户自动就有这 4 个码 —— 但**存量租户**的 OWNER 角色是在这 4 个码登记之前建的，
-- 不会自动获得它们 ⇒ 新接入的 create / update / revoke 对既有租户的 OWNER 不可见，
-- 迁移上线后这些租户会突然「什么都点不动」。
--
-- 用 LIKE 'platform.webhook.%' 扫**整个集合**，而不是只补 read 一条：
--   · 覆盖本迁移登记的全部 4 个动作（read / create / update / revoke）；
--   · 幂等 —— 重复执行不产生重复行（ON CONFLICT DO NOTHING）。
--
-- 与 V3 / V8 / V104 / V330 / V378 同口径：租户所有者始终拥有全部页面权限。
--
-- ---------------------------------------------------------------------------
-- 五、幂等
-- ---------------------------------------------------------------------------
--
-- 三段式全部带 ON CONFLICT DO NOTHING：同一段 SQL 跑两次不报错、不产生重复行。

-- ---------------------------------------------------------------------------
-- 1. 页面资源（菜单入口）
-- ---------------------------------------------------------------------------
INSERT INTO page_resource(code,name) VALUES ('platform.webhook','事件订阅')
ON CONFLICT (code) DO NOTHING;

-- ---------------------------------------------------------------------------
-- 2. 权限码（4 个动作）
-- ---------------------------------------------------------------------------
INSERT INTO permission SELECT 'platform.webhook.'||action,'platform.webhook',action
FROM unnest(ARRAY['read','create','update','revoke']::text[]) action
ON CONFLICT (code) DO NOTHING;

-- ---------------------------------------------------------------------------
-- 3. 存量 OWNER 补权（覆盖 platform.webhook.% 整个集合）
-- ---------------------------------------------------------------------------
INSERT INTO role_permission SELECT r.tenant_id,r.id,p.code FROM role r CROSS JOIN permission p
 WHERE r.code='OWNER' AND p.code LIKE 'platform.webhook.%' ON CONFLICT DO NOTHING;
