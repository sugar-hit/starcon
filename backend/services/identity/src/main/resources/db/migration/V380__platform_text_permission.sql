-- ===========================================================================
-- V380 · platform_text_permission —— 18.4.2.1「文本与翻译」的 platform.text 权限码登记
-- ===========================================================================
--
-- 蓝图 18「集成开放与智能自动化」→ 18.4「AI 与智能」→ 18.4.2「AI 能力」→ 18.4.2.1「文本与翻译」。
--
-- ---------------------------------------------------------------------------
-- 一、为什么需要这个迁移（补的是既有缺口，不是本车道扩大范围）
-- ---------------------------------------------------------------------------
--
-- platform 服务的 TextTranslationController 用
--     access.require(bearer, "platform.text." + permission)
-- 强制鉴权，端点实际用到 5 个动作：read / create / update / confirm / publish。
--
-- 但 identity 服务的 permission 表里**从来没有注册过 platform.text 任何一行** ——
-- 而 role_permission.permission_code 有指向 permission(code) 的外键 ——
-- 于是「没有任何角色可能持有 platform.text.read」，
-- 这些端点在真实环境里恒 403。
--
-- （与 V378 登记 platform.app.* 的缺口**完全同构**：那一批同样是「服务已交付、
--   权限码没登记」，上一任车道用假 identity 服务做集成测试，所以测试全绿也没暴露。）
--
-- 本迁移只做一件事：把这 5 个码登记进 identity 的权限码表。
--
-- ---------------------------------------------------------------------------
-- 二、登记哪几个码
-- ---------------------------------------------------------------------------
--
--   platform.text.read     读任务 / 草稿 / 术语表 / 违禁词表 / 规则 / 模板 / 检查结果 / 能力声明
--   platform.text.create   建任务
--   platform.text.update   编辑译文（追加草稿版本）、改术语 / 词 / 规则 / 模板
--   platform.text.confirm  人工确认译文（**发布前的硬门槛**）
--   platform.text.publish  发布已确认的译文
--   platform.text.reject   驳回译文（终态）
--
-- 刻意**只**登记这 6 个动作：没有端点的权限码不注册
-- （与 identity V104 / V53 / V330 / V378 同一纪律）。
--
-- 「人工确认」与「发布」是**两个独立的码**，而不是合成一个 update：
-- 蓝图加粗句「**翻译结果必须人工确认后发布**」说的是一道**门槛** ——
-- 能改文案的人不该顺手把「已确认」也点了。确认与发布分开授权，
-- 门槛才真的拦得住人，而不是拦得住状态机。
--
-- 「驳回」也**独立**成一个码：驳回是终态（这条任务不再走确认 / 发布流程），
-- 能改内容的人不该顺手把别人的稿子毙掉。
--
-- ---------------------------------------------------------------------------
-- 三、为什么 page_code 取 platform.text
-- ---------------------------------------------------------------------------
--
-- permission.page_code 有外键指向 page_resource(code)，所以必须先插页面行。
--
-- page_resource 对应**菜单入口**，不是动作。
-- 「文本与翻译」是 18.4.2.1 的**同一个页面**（术语表 / 任务列表 / 译文工作区在同一处管理），
-- 不是五个页面 —— 拆成五个 page_resource 会在菜单里多出四个与「文本与翻译」重复的条目。
--
-- 前缀取 platform.text 而不是 copilot.text：本模块的权限码由 **platform 服务**消费
-- （platform.text.read），与 catalog.spu / warehouse.facilities / platform.app 的
-- 「服务名.页面」口径一致；权限码跟着**消费它的服务**走，才能在审计时回答
-- 「谁被授权改这一类东西」。
--
-- ---------------------------------------------------------------------------
-- 四、为什么必须给存量 OWNER 补权（这是本迁移最容易漏的一步）
-- ---------------------------------------------------------------------------
--
-- 新建子租户由 create_child（V47）把 permission 表里的**全部**权限码授给 OWNER，
-- 所以新租户自动就有这 5 个码 —— 但**存量租户**的 OWNER 角色是在这 5 个码登记之前建的，
-- 不会自动获得它们 ⇒ 新接入的 create / update / confirm / publish 对既有租户的 OWNER 不可见，
-- 迁移上线后这些租户会突然「什么都点不动」。
--
-- 用 LIKE 'platform.text.%' 扫**整个集合**，而不是只补 read 一条：
--   · 覆盖本迁移登记的全部 6 个动作（read / create / update / confirm / publish / reject）；
--   · 幂等 —— 重复执行不产生重复行（ON CONFLICT DO NOTHING）。
--
-- 与 V3 / V8 / V104 / V330 / V378 同口径：租户所有者始终拥有全部页面权限。
--
-- ---------------------------------------------------------------------------
-- 五、幂等
-- ---------------------------------------------------------------------------
--
-- 三段式全部带 ON CONFLICT DO NOTHING：同一段 SQL 跑两次不报错、不产生重复行。
--
-- ⚠️ **不碰 platform.app.***：那是 18.1.1.1 的权限码，由 V378 登记。
--   本迁移**只**动 platform.text.% —— 两个批次的权限码互不覆盖。

-- ---------------------------------------------------------------------------
-- 1. 页面资源（菜单入口）
-- ---------------------------------------------------------------------------
INSERT INTO page_resource(code,name) VALUES ('platform.text','文本与翻译')
ON CONFLICT (code) DO NOTHING;

-- ---------------------------------------------------------------------------
-- 2. 权限码（5 个动作）
-- ---------------------------------------------------------------------------
INSERT INTO permission SELECT 'platform.text.'||action,'platform.text',action
FROM unnest(ARRAY['read','create','update','confirm','publish','reject']::text[]) action
ON CONFLICT (code) DO NOTHING;

-- ---------------------------------------------------------------------------
-- 3. 存量 OWNER 补权（覆盖 platform.text.% 整个集合）
-- ---------------------------------------------------------------------------
INSERT INTO role_permission SELECT r.tenant_id,r.id,p.code FROM role r CROSS JOIN permission p
 WHERE r.code='OWNER' AND p.code LIKE 'platform.text.%' ON CONFLICT DO NOTHING;
