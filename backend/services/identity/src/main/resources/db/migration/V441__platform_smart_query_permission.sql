-- ===========================================================================
-- V441 · platform_smart_query_permission —— 18.4.1.2「智能查询」的权限码登记
-- ===========================================================================
--
-- 蓝图 18「集成开放与智能自动化」→ 18.4「AI 与智能」→ 18.4.1「智能问答」→ 18.4.1.2。
--
-- ---------------------------------------------------------------------------
-- 一、为什么需要这个迁移
-- ---------------------------------------------------------------------------
--
-- platform 服务的 SmartQueryController 用
--     access.require(bearer, "platform.smart_query." + permission)
-- 强制鉴权，端点实际用到 3 个动作：read / create / update。
--
-- 但 identity 服务的 permission 表里**从来没有注册过 platform.smart_query 任何一行** ——
-- 而 role_permission.permission_code 有指向 permission(code) 的外键 ——
-- 于是「没有任何角色可能持有 platform.smart_query.read」，
-- 这些端点在真实环境里恒 403。
--
-- （与 V378 登记 platform.app.*、V380 登记 platform.text.*、V419 登记
--   platform.automation_rule.*、V429 / V430 登记 platform.ai-diagnosis.* /
--   platform.ai-effect.*、V438 登记 platform.assistant.* 的缺口**完全同构**。）
--
-- 本迁移只做一件事：把这 3 个码登记进 identity 的权限码表。
--
-- ---------------------------------------------------------------------------
-- 二、登记哪几个码
-- ---------------------------------------------------------------------------
--
--   platform.smart_query.read    读能力声明 / 受控语义层目录 / 查询台账 / 常用查询
--   platform.smart_query.create  执行一次查询（写查询台账 + 明细依据 + 在 13.6.1.1 建报表草稿）
--   platform.smart_query.update  保存为常用查询 / 取消常用查询 / 重跑常用查询
--
-- 刻意**只**登记这 3 个动作：没有端点的权限码不注册
-- （与 identity V104 / V53 / V330 / V378 / V380 / V419 / V438 同一纪律）。
--
-- 「读」与「执行」是**两个独立的码**，理由与 18.4.1.1 的「读会话 / 提问」同源：
-- 执行一次查询会写台账（查询条件 + 明细依据）**并且在下游 13.6.1.1 里建报表草稿**，
-- 是**写动作**；而读台账 / 读语义层目录是读动作。
-- 「保存为常用查询」是第三个独立动作（改的是**自己的**常用查询清单）。
--
-- ⚠️ **本车道不登记「执行报表 / 导出 / 分享」权限码** —— 那些属 13.6.1.1 / 13.6.2.1，
--   权限码归 reporting / identity 各自的域，本迁移不越界登记。
--
-- ---------------------------------------------------------------------------
-- 三、为什么 page_code 取 platform.smart_query
-- ---------------------------------------------------------------------------
--
-- permission.page_code 有外键指向 page_resource(code)，所以必须先插页面行。
--
-- page_resource 对应**菜单入口**，不是动作。
-- 「智能查询」是 18.4.1.2 的**同一个页面**（语义层目录 / 提问 / 常用查询在同一处），
-- 不是一个动作一个页面。
--
-- 前缀取 platform.smart_query：权限码由 **platform 服务**消费
-- （platform.smart_query.read），与 catalog.spu / warehouse.facilities /
-- platform.app / platform.text / platform.assistant 的「服务名.页面」口径一致。
--
-- ⚠️ **不碰 channel.* 与 platform.* 的既有前缀**：本迁移**只**动
--   platform.smart_query.%，与其它车道互不覆盖。
--
-- ---------------------------------------------------------------------------
-- 四、为什么必须给存量 OWNER 补权（这是本迁移最容易漏的一步）
-- ---------------------------------------------------------------------------
--
-- 新建子租户由 create_child（V47）把 permission 表里的**全部**权限码授给 OWNER，
-- 所以新租户自动就有这 3 个码 —— 但**存量租户**的 OWNER 角色是在这 3 个码登记之前建的，
-- 不会自动获得它们 ⇒ 迁移上线后这些租户会突然「什么都点不动」。
--
-- 用 LIKE 'platform.smart_query.%' 扫**整个集合**，而不是只补 read 一条：
--   · 覆盖本迁移登记的全部 3 个动作；
--   · 幂等 —— 重复执行不产生重复行（ON CONFLICT DO NOTHING）。
--
-- 与 V3 / V8 / V104 / V330 / V378 / V380 / V419 / V430 / V438 同口径：
-- 租户所有者始终拥有全部页面权限。
--
-- ---------------------------------------------------------------------------
-- 五、幂等
-- ---------------------------------------------------------------------------
--
-- 三段式全部带 ON CONFLICT DO NOTHING：同一段 SQL 跑两次不报错、不产生重复行。
-- ===========================================================================

-- ---------------------------------------------------------------------------
-- 1. 页面资源（菜单入口）
-- ---------------------------------------------------------------------------
INSERT INTO page_resource(code,name) VALUES ('platform.smart_query','智能查询')
ON CONFLICT (code) DO NOTHING;

-- ---------------------------------------------------------------------------
-- 2. 权限码（3 个动作）
-- ---------------------------------------------------------------------------
INSERT INTO permission SELECT 'platform.smart_query.'||action,'platform.smart_query',action
FROM unnest(ARRAY['read','create','update']::text[]) action
ON CONFLICT (code) DO NOTHING;

-- ---------------------------------------------------------------------------
-- 3. 存量 OWNER 补权（覆盖 platform.smart_query.% 整个集合）
-- ---------------------------------------------------------------------------
INSERT INTO role_permission SELECT r.tenant_id,r.id,p.code FROM role r CROSS JOIN permission p
 WHERE r.code='OWNER' AND p.code LIKE 'platform.smart_query.%' ON CONFLICT DO NOTHING;
