-- ===========================================================================
-- V416 · platform_payment_permission —— 18.2.2.1「支付与资金」的 platform.payment 权限码登记
-- ===========================================================================
--
-- 蓝图 18「集成开放与智能自动化」→ 18.2「财务与资金」→ 18.2.2「支付与资金」→ 18.2.2.1。
--
-- ---------------------------------------------------------------------------
-- 一、为什么需要这个迁移
-- ---------------------------------------------------------------------------
--
-- platform 服务的 PaymentFundsController 用
--     access.require(bearer, "platform.payment." + permission)
-- 强制鉴权，端点实际用到 5 个动作：read / create / update / execute / sync。
--
-- 但 identity 服务的 permission 表里**从来没有注册过 platform.payment 任何一行** ——
-- 而 role_permission.permission_code 有指向 permission(code) 的外键 ——
-- 于是「没有任何角色可能持有 platform.payment.read」，
-- 这些端点在真实环境里恒 403。
--
-- （与 V378 登记 platform.app.*、V380 登记 platform.text.*、V382 登记 platform.finance.*、
--   V411–V414 登记 platform.api.* / platform.webhook.* / platform.delivery.* /
--   platform.call.* 的缺口**完全同构**：那几批同样是「服务已交付、权限码没登记」。）
--
-- 本迁移只做一件事：把这 5 个码登记进 identity 的权限码表。
--
-- ---------------------------------------------------------------------------
-- 二、登记哪几个码
-- ---------------------------------------------------------------------------
--
--   platform.payment.read    读服务商配置 / 余额 / 流水 / 手续费 / 汇率 / 操作记录 / 能力声明
--   platform.payment.create  登记服务商配置、登记收款、导入余额、导入手续费、查询汇率
--   platform.payment.update  改服务商配置、停用服务商配置
--   platform.payment.execute **付款执行**（钱要出去）
--   platform.payment.sync    **直连同步**（服务商侧余额 / 手续费明细 / 汇率报价）
--
-- 刻意**只**登记这 5 个动作：没有端点的权限码不注册
-- （与 identity V104 / V53 / V330 / V378 / V380 / V382 同一纪律）。
--
-- 「执行」与「同步」是**两个独立的码**，理由与 18.2.1.1 的「导出 / 推送」同源：
--   · 「执行」= **钱要动**。点一下就是一次对外付款，影响面最大，必须单独授权；
--   · 「同步」= **拉数据回来**（余额 / 手续费 / 汇率报价）。只读不动钱。
-- 能配服务商档案的人不该顺手就能发起付款。
--
-- ⚠️ platform.payment.sync 目前**恒 409**（支付服务商适配器未接入，
--   见 V416__payment_and_funds.sql 第 0 节）—— 但权限码**照样登记**：
--   端点要在权限校验**之后**如实答「未接入」，而不是先被 403 挡掉。
--   先答 403 会让运营以为「有权限就能同步」，从而去找「是不是少了权限」。
--
-- ---------------------------------------------------------------------------
-- 三、为什么 page_code 取 platform.payment
-- ---------------------------------------------------------------------------
--
-- permission.page_code 有外键指向 page_resource(code)，所以必须先插页面行。
--
-- page_resource 对应**菜单入口**，不是动作。
-- 「支付与资金」是 18.2.2.1 的**同一个页面**（服务商配置 / 余额 / 流水 / 手续费 /
-- 汇率 / 操作记录在同一处管理），不是一个动作一个页面。
--
-- 前缀取 platform.payment 而不是 finance.payment：本模块的权限码由
-- **platform 服务**消费（platform.payment.read），与 catalog.spu / warehouse.facilities /
-- platform.app / platform.text / platform.finance 的「服务名.页面」口径一致；
-- 权限码跟着**消费它的服务**走，才能在审计时回答「谁被授权动钱」。
--
-- ⚠️ **不碰 finance.* 与 platform.finance.* / platform.app.* / platform.text.*：
--   finance.* 是 12 财务核算服务自己的权限码，platform.finance.* 是 18.2.1.1、
--   platform.app.* 是 18.1.1.1、platform.text.* 是 18.4.2.1 ——
--   本迁移**只**动 platform.payment.%，几批的权限码互不覆盖。
--
-- ---------------------------------------------------------------------------
-- 四、为什么必须给存量 OWNER 补权（这是本迁移最容易漏的一步）
-- ---------------------------------------------------------------------------
--
-- 新建子租户由 create_child（V47）把 permission 表里的**全部**权限码授给 OWNER，
-- 所以新租户自动就有这 5 个码 —— 但**存量租户**的 OWNER 角色是在这 5 个码登记之前建的，
-- 不会自动获得它们 ⇒ 迁移上线后这些租户会突然「什么都点不动」。
--
-- 用 LIKE 'platform.payment.%' 扫**整个集合**，而不是只补 read 一条：
--   · 覆盖本迁移登记的全部 5 个动作；
--   · 幂等 —— 重复执行不产生重复行（ON CONFLICT DO NOTHING）。
--
-- 与 V3 / V8 / V104 / V330 / V378 / V380 / V382 同口径：租户所有者始终拥有全部页面权限。
--
-- ---------------------------------------------------------------------------
-- 五、幂等
-- ---------------------------------------------------------------------------
--
-- 三段式全部带 ON CONFLICT DO NOTHING：同一段 SQL 跑两次不报错、不产生重复行。
-- ===========================================================================

-- ---------------------------------------------------------------------------
-- 1. 页面资源（菜单入口）
-- ---------------------------------------------------------------------------
INSERT INTO page_resource(code,name) VALUES ('platform.payment','支付与资金')
ON CONFLICT (code) DO NOTHING;

-- ---------------------------------------------------------------------------
-- 2. 权限码（5 个动作）
-- ---------------------------------------------------------------------------
INSERT INTO permission SELECT 'platform.payment.'||action,'platform.payment',action
FROM unnest(ARRAY['read','create','update','execute','sync']::text[]) action
ON CONFLICT (code) DO NOTHING;

-- ---------------------------------------------------------------------------
-- 3. 存量 OWNER 补权（覆盖 platform.payment.% 整个集合）
-- ---------------------------------------------------------------------------
INSERT INTO role_permission SELECT r.tenant_id,r.id,p.code FROM role r CROSS JOIN permission p
 WHERE r.code='OWNER' AND p.code LIKE 'platform.payment.%' ON CONFLICT DO NOTHING;
