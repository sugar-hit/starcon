-- ===========================================================================
-- 8.1.1.3 仓库配置：仓库作业参数的读写权限码
-- ===========================================================================
--
-- ADR-0005：L3 子功能 = 一张 page_resource，按角色配 CRUD。
-- 蓝图 08 的 8.1「仓库与库位」是 L3，本模块是它的第三个 L4。
--
-- ---------------------------------------------------------------------------
-- 这是 8.1.1.1 文件头点名要本条车道兑现的交接
-- ---------------------------------------------------------------------------
-- identity V69 在文件头写死了分工：
--   「刻意只注册 read + create，不注册 update / delete。
--     改仓库属性属 8.1.1.2 详情、行为参数属 8.1.1.3 配置，两条车道落地时各自补自己的码。」
-- V77 已经兑现了前半句（warehouse.facilities.update）。本迁移兑现后半句。
--
-- ---------------------------------------------------------------------------
-- 为什么是独立的 warehouse.facilities.config 而不是复用 update
-- ---------------------------------------------------------------------------
--   warehouse.facilities.update（V77, 8.1.1.2）= 改仓库**属性**：
--       名称、国家、时区、地址五列、启用状态。
--   warehouse.facilities.config（本迁移, 8.1.1.3）= 改仓库**作业行为**：
--       是否批次/序列号、拣货策略、默认复核比例、是否拆零、工作时段与班次。
--
-- 两者风险面不同，逐条说清为什么不能合并成一个码：
--
--   1. **改错了的后果不同。**把地址填错是可恢复的录入事故（改回来就行）；
--      把默认复核比例从 0 调到 1，或者把拣货策略从 ORDER 改成 WAVE，
--      会让**当天之后所有出库作业**按另一套方式执行 —— 它不是一条记录的字段，
--      是作业契约。同一批货已经按旧策略拣过的部分不会被改回来。
--   2. **授权粒度的现实需要不同。**维护班次的人（仓库主管，盯着排班表）
--      与维护仓库档案的人（行政/物流对接，填地址换时区）通常是不同岗位。
--      共用一个码会让「谁能调班次」和「谁能改地址」变成同一个问题，
--      授权界面上无法分开授予 —— 而 V69 已经因为同一类理由拒绝复用
--      warehouse.inventory（「新增仓库是主数据写入、7.1.x 是库存聚合只读」）。
--   3. **归属的模块号不同。**前者归 8.1.1.2，后者归 8.1.1.3。
--      权限码跟着模块走，才能在审计时回答「谁被授权改这一类东西」。
--
-- 读端点复用 warehouse.facilities.read：本模块读的是**自己刚写进去的当前态**
-- （配置、班次、变更历史），它的可见范围不比「能看仓库详情」更宽 ——
-- 谁能看到「这个仓改过复核比例」不该是一个独立授权决定，
-- 独立授权只会制造「有 read 没有 read-of-history」这种没人想得清的组合。
--
-- ---------------------------------------------------------------------------
-- 刻意只注册 read + config，不注册 delete
-- ---------------------------------------------------------------------------
-- 与 identity V53 数据字典、8.1.1.2 的 V77 同一纪律：**没有端点的权限码不注册**。
-- 本模块**没有**任何 DELETE 端点：班次的调整出口是停用（enabled=false），
-- 配置的出口是改值而不是删行 —— 删掉配置行等于让这个仓「退回没有配置」，
-- 而作业单已经在按那套参数执行了。
--
-- ---------------------------------------------------------------------------
-- 为什么复用 warehouse.facilities 页面而不新建 page_resource
-- ---------------------------------------------------------------------------
-- 8.1.1.3 是 8.1.1.1 的**同一个页面**（/warehouse/facilities 下的配置视图），
-- 不是新页面。ADR-0005 的 page_resource 对应菜单入口，配置视图挂在仓库档案之下
-- 不构成新入口 —— 插一行会在菜单里多出一个与「仓库档案」重复的条目。
-- 与 V77 完全同构：permission.page_code 有指向 page_resource 的外键，
-- 所以这里能直接插权限行而不必先插页面。

INSERT INTO permission VALUES ('warehouse.facilities.config','warehouse.facilities','config')
ON CONFLICT (code) DO NOTHING;

-- 与 V8 / V53 / V69 / V77 同规则：租户所有者始终拥有全部页面权限，
-- 否则新接入的动作对既有租户不可见（存量 OWNER 角色也要补上）。
-- 用 LIKE 重新扫一遍整个 warehouse.facilities.* 集合是幂等的：
-- read / create（V69）与 update（V77）已在，这里把 config 一并带上。
INSERT INTO role_permission SELECT r.tenant_id,r.id,p.code FROM role r CROSS JOIN permission p
 WHERE r.code='OWNER' AND p.code LIKE 'warehouse.facilities.%' ON CONFLICT DO NOTHING;
