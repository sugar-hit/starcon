-- ===========================================================================
-- 18.1.3.1 导入导出任务：platform.io 权限码登记
-- ===========================================================================
--
-- 蓝图 18「集成开放与智能自动化」→ 18.1「开放平台」→ 18.1.3「数据交换」→ 18.1.3.1「导入导出任务」。
--
-- ---------------------------------------------------------------------------
-- 一、为什么需要这个迁移（补的是既有缺口，不是本车道扩大范围）
-- ---------------------------------------------------------------------------
--
-- platform 服务的 ImportExportController 用
--     access.require(bearer, "platform.io." + permission)
-- 强制鉴权，实际只用到 4 个动作：read / create / execute / download。
--
-- 但 identity 服务的 permission 表里**从来没有注册过 platform.io 任何一行** ——
-- 而 role_permission.permission_code 有指向 permission(code) 的外键 ——
-- 于是「没有任何角色可能持有 platform.io.read」，
-- 这些端点在真实环境里恒 403（与 V378 登记 platform.app.*、V411 登记
-- platform.api-catalog.*、V412 登记 platform.webhook.*、V414 登记
-- platform.call-monitor.* 时遇到的缺口**完全同构**）。
--
-- ---------------------------------------------------------------------------
-- 二、登记哪几个码
-- ---------------------------------------------------------------------------
--
--   platform.io.read      读任务列表 / 任务详情 / 能力声明 / 数据域目录 /
--                         失败行明细 / 模板列表
--   platform.io.create    **发起**导入导出任务（导出：选数据域与范围；
--                         导入：上传文件）
--   platform.io.execute   触发执行（开始一次导入 / 取消任务 / 清理过期文件）
--   platform.io.download  **下载文件**（导出结果 / 失败行报告 / 导入模板）
--
-- 刻意**只**登记这 4 个动作：没有端点的权限码不注册
-- （与 identity V104 / V53 / V330 同一纪律）。
--
-- 「下载」是**独立**的一个码而不是 read：文件要**离开本系统**（进用户本地文件），
-- 而读任务记录留在系统内 —— 能看「有一份导出」与能把它拿走，是两件事。
-- 一个「能看导出记录就能把全量客户数据下载走」的权限模型，在数据出境合规上是不可接受的。
--
-- ⚠️ AccessService 的判据要求同一个 grant 里同时有该动作与对应资源的 `.read` ——
--    所以持有 platform.io.download / platform.io.execute 的角色
--    **同时**必须持有 platform.io.read。
--    这是有意的：能处置任务的人至少得能看懂任务是什么。
--
-- ---------------------------------------------------------------------------
-- 三、为什么 page_code 取 platform.io
-- ---------------------------------------------------------------------------
--
-- permission.page_code 有外键指向 page_resource(code)，所以必须先插页面行。
--
-- page_resource 对应**菜单入口**，不是动作。
-- 「导入导出任务」是 18.1.3「数据交换」的**同一个页面**
-- （任务列表 / 数据域选择 / 失败行报告 / 模板下载在同一处管理），
-- 不是两个页面 —— 拆成两个 page_resource 会在菜单里多出一个与「导入导出任务」重复的条目。
--
-- 前缀取 platform.io（不是 identity.io）：本模块的权限码由
-- **platform 服务**消费（platform.io.read），与 catalog.spu / warehouse.facilities /
-- platform.app / platform.text / platform.finance / platform.api-catalog /
-- platform.webhook / platform.call-monitor 的「服务名.页面」口径一致；
-- 权限码跟着**消费它的服务**走，才能在审计时回答「谁被授权看这一类东西」。
--
-- ---------------------------------------------------------------------------
-- 四、为什么必须给存量 OWNER 补权（这是本迁移最容易漏的一步）
-- ---------------------------------------------------------------------------
--
-- 新建子租户由 create_child（V47）把 permission 表里的**全部**权限码授给 OWNER，
-- 所以新租户自动就有这 4 个码 —— 但**存量租户**的 OWNER 角色是在这 4 个码登记之前建的，
-- 不会自动获得它们 ⇒ 新接入的 read / create / execute / download 对既有租户的
-- OWNER 不可见，迁移上线后这些租户会突然「什么都点不动」。
--
-- 用 LIKE 'platform.io.%' 扫**整个集合**，而不是只补 read 一条：
--   · 覆盖本迁移登记的全部 4 个动作（read / create / execute / download）；
--   · 幂等 —— 重复执行不产生重复行（ON CONFLICT DO NOTHING）。
--
-- 与 V3 / V8 / V104 / V330 / V414 同口径：租户所有者始终拥有全部页面权限。
--
-- ---------------------------------------------------------------------------
-- 五、幂等
-- ---------------------------------------------------------------------------
--
-- 三段式全部带 ON CONFLICT DO NOTHING：同一段 SQL 跑两次不报错、不产生重复行。
--
-- ---------------------------------------------------------------------------
-- 1. 页面资源（菜单入口）
-- ---------------------------------------------------------------------------
INSERT INTO page_resource(code,name) VALUES ('platform.io','导入导出任务')
ON CONFLICT (code) DO NOTHING;

-- ---------------------------------------------------------------------------
-- 2. 权限码（4 个动作）
-- ---------------------------------------------------------------------------
INSERT INTO permission SELECT 'platform.io.'||action,'platform.io',action
FROM unnest(ARRAY['read','create','execute','download']::text[]) action
ON CONFLICT (code) DO NOTHING;

-- ---------------------------------------------------------------------------
-- 3. 存量 OWNER 补权（覆盖 platform.io.% 整个集合）
-- ---------------------------------------------------------------------------
INSERT INTO role_permission SELECT r.tenant_id,r.id,p.code FROM role r CROSS JOIN permission p
 WHERE r.code='OWNER' AND p.code LIKE 'platform.io.%' ON CONFLICT DO NOTHING;
