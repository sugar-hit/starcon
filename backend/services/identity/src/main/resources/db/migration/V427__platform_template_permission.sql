-- ===========================================================================
-- V427 · platform_template_permission —— 18.5.1.1「模板管理」的 platform.template 权限码登记
-- ===========================================================================
--
-- 蓝图 18「集成开放与智能自动化」→ 18.5「通知模板」→ 18.5.1「模板管理」。
--
-- ---------------------------------------------------------------------------
-- 一、为什么需要这个迁移（补的是既有缺口，不是本车道扩大范围）
-- ---------------------------------------------------------------------------
--
-- platform 服务的 NotificationTemplateController 用
--     access.require(bearer, "platform.template." + permission)
-- 强制鉴权，端点实际用到 4 个动作：read / create / update / delete。
--
-- 但 identity 服务的 permission 表里**从来没有注册过 platform.template 任何一行** ——
-- 而 role_permission.permission_code 有指向 permission(code) 的外键 ——
-- 于是「没有任何角色可能持有 platform.template.read」，
-- 这些端点在真实环境里恒 403。
--
-- （与 V378 登记 platform.app.*、V380 登记 platform.text.* 的缺口**完全同构**：
--   那一批同样是「服务已交付、权限码没登记」，测试用假 identity 服务时全绿也没暴露。）
--
-- 本迁移只做一件事：把这 4 个码登记进 identity 的权限码表。
--
-- ---------------------------------------------------------------------------
-- 二、登记哪几个码
-- ---------------------------------------------------------------------------
--
--   platform.template.read    读模板 / 版本 / 渲染预览 / 按时刻解析 / 能力声明 / 上游文案资产
--   platform.template.create  新建模板（同时落下第 1 版内容）
--   platform.template.update  编辑（= **新增版本**）/ 启用某个版本 / 停用 / 改名称与说明
--   platform.template.delete  删除模板（= **停用 + 归档**；**不物理删**版本行）
--
-- 刻意**只**登记这 4 个动作：没有端点的权限码不注册
-- （与 identity V104 / V53 / V330 / V378 / V380 同一纪律）。
--
-- 「删除」为什么还留着一个 delete 码：这个 delete **不是物理删**（版本行是历史通知的
-- 「当时内容」依据，删了就解释不清了），它是「停用 + 归档」。但它仍然是**一个会改变
-- 东西的动作** —— 让有权改内容的人顺手把模板归档掉不是好事，所以它独立成一个码。
--
-- 「编辑」为什么只是 update 一个码：编辑 = **新增一个版本**，老版本不可改 ——
-- 版本不可篡改由**数据层**（权限 + 触发器）兜底，不需要再拆一个权限码。
--
-- ---------------------------------------------------------------------------
-- 三、为什么 page_code 取 platform.template
-- ---------------------------------------------------------------------------
--
-- permission.page_code 有外键指向 page_resource(code)，所以必须先插页面行。
--
-- page_resource 对应**菜单入口**，不是动作。
-- 「模板管理」是 18.5.1.1 的**同一个页面**（模板列表 / 版本历史 / 编辑 / 渲染预览在同一处），
-- 不是四个页面 —— 拆成四个 page_resource 会在菜单里多出三个与「模板管理」重复的条目。
--
-- 前缀取 platform.template 而不是 notify.template：本模块的权限码由 **platform 服务**消费
-- （platform.template.read），与 catalog.spu / platform.app / platform.text 的
-- 「服务名.页面」口径一致；权限码跟着**消费它的服务**走，才能在审计时回答
-- 「谁被授权改这一类东西」。
--
-- ⚠️ **与 18.4.2.1 的 platform.text 不是一件事**：
--   那边的模板是「客服回复**草稿**」（AI 翻译链路的产物），这边是「**通知与消息模板**」
--   （按场景 × 语言组织、版本化、可按时刻解析）。两个 page_resource、两个前缀。
--
-- ---------------------------------------------------------------------------
-- 四、为什么必须给存量 OWNER 补权（这是本迁移最容易漏的一步）
-- ---------------------------------------------------------------------------
--
-- 新建子租户由 create_child（V47）把 permission 表里的**全部**权限码授给 OWNER，
-- 所以新租户自动就有这 4 个码 —— 但**存量租户**的 OWNER 角色是在这 4 个码登记之前建的，
-- 不会自动获得它们 ⇒ 新接入的 create / update / delete 对既有租户的 OWNER 不可见，
-- 迁移上线后这些租户会突然「什么都点不动」。
--
-- 用 LIKE 'platform.template.%' 扫**整个集合**，而不是只补 read 一条：
--   · 覆盖本迁移登记的全部 4 个动作（read / create / update / delete）；
--   · 幂等 —— 重复执行不产生重复行（ON CONFLICT DO NOTHING）。
--
-- 与 V3 / V8 / V104 / V330 / V378 / V380 同口径：租户所有者始终拥有全部页面权限。
--
-- ---------------------------------------------------------------------------
-- 五、幂等
-- ---------------------------------------------------------------------------
--
-- 三段式全部带 ON CONFLICT DO NOTHING：同一段 SQL 跑两次不报错、不产生重复行。
--
-- ⚠️ **不碰 platform.text.***：那是 18.4.2.1 的权限码，由 V380 登记。
--   本迁移**只**动 platform.template.% —— 两个模块的权限码互不覆盖。

-- ---------------------------------------------------------------------------
-- 1. 页面资源（菜单入口）
-- ---------------------------------------------------------------------------
INSERT INTO page_resource(code,name) VALUES ('platform.template','模板管理')
ON CONFLICT (code) DO NOTHING;

-- ---------------------------------------------------------------------------
-- 2. 权限码（4 个动作）
-- ---------------------------------------------------------------------------
INSERT INTO permission SELECT 'platform.template.'||action,'platform.template',action
FROM unnest(ARRAY['read','create','update','delete']::text[]) action
ON CONFLICT (code) DO NOTHING;

-- ---------------------------------------------------------------------------
-- 3. 存量 OWNER 补权（覆盖 platform.template.% 整个集合）
-- ---------------------------------------------------------------------------
INSERT INTO role_permission SELECT r.tenant_id,r.id,p.code FROM role r CROSS JOIN permission p
 WHERE r.code='OWNER' AND p.code LIKE 'platform.template.%' ON CONFLICT DO NOTHING;
