-- ===========================================================================
-- V432 · crm_customer_permission —— 15.3.1.1「客户列表」的 crm.customers 权限码登记
-- ===========================================================================
--
-- 蓝图 15「客户与客服」→ 15.3 客户档案 → 15.3.1 客户主档 → 15.3.1.1 客户列表。
--
-- ---------------------------------------------------------------------------
-- 一、为什么需要这个迁移
-- ---------------------------------------------------------------------------
--
-- crm 服务的 CustomerListController 用
--     access.require(bearer, "crm.customers.read" / "crm.customers.update")
-- 强制鉴权，端点实际用到三个动作：
--
--   crm.customers.read       读客户列表、分层统计、筛选项、能力声明
--   crm.customers.update     从上游刷新客户档案、登记 / 修正联系方式
--   crm.customers.pii.read   **看明文联系方式**（脱敏是默认，见下）
--
-- 而 identity 服务的 permission 表里**从来没有注册过 crm.* 任何一行** ——
-- 而 role_permission.permission_code 有指向 permission(code) 的外键 ——
-- 于是「没有任何角色可能持有 crm.customers.read」，
-- 这些端点在真实环境里恒 403。
--
-- （与 V418 登记 platform.external.*、V378 / V380 / V382 登记 platform.app / text /
--   finance.* 的缺口**完全同构**：那几批同样是「服务已交付、权限码没登记」。）
--
-- 本迁移只做一件事：把这 3 个码登记进 identity 的权限码表。
--
-- ---------------------------------------------------------------------------
-- 二、三个码的分工（尤其是第三个）
-- ---------------------------------------------------------------------------
--
--   crm.customers.read       读列表与统计。**返回的联系方式是脱敏形态**
--                             （a***@***.com / 138****1234）。
--   crm.customers.update     刷新客户档案、登记联系方式。
--   crm.customers.pii.read   **明文联系方式**：这是「显式授权才给完整值」的那把钥匙 ——
--                             蓝图加粗句「列表默认脱敏显示联系方式，需要显式授权才完整展示」
--                             在权限码这一层的落点。
--                             刻意与 read **分开**：能看客户列表 ≠ 能看手机号。
--
-- ---------------------------------------------------------------------------
-- 三、为什么 page_code 取 crm.customers
-- ---------------------------------------------------------------------------
--
-- permission.page_code 有外键指向 page_resource(code)，所以必须先插页面行。
-- page_resource 对应**菜单入口**，不是动作 —— 「客户列表」是 15.3.1 下的
-- **同一个页面**（列表 + 分层统计 + 联系方式登记在同一处管理），不是一个动作一个页面。
-- 前缀取 crm.customers 而不是 crm.customer_list：与
-- catalog.spu / warehouse.facilities / platform.app 的「服务名.页面」口径一致；
-- 权限码跟着**消费它的服务**走，才能在审计时回答「谁被授权看客户明文联系方式」。
--
-- ⚠️ **不碰 crm.* 的既有前缀**：crm.tag.*（15.3.2.1 客户标签）、
-- crm.contact.*（15.3.2.2 接触记录）等既有码由各自的模块登记，
-- 本迁移**只**动 crm.customers.%。
--
-- ---------------------------------------------------------------------------
-- 四、为什么必须给存量 OWNER 补权（这是本迁移最容易漏的一步）
-- ---------------------------------------------------------------------------
--
-- 新建子租户由 create_child（V47）把 permission 表里的**全部**权限码授给 OWNER，
-- 所以新租户自动就有这 3 个码 —— 但**存量租户**的 OWNER 角色是在这 3 个码登记之前建的，
-- 不会自动获得它们 ⇒ 迁移上线后这些租户会突然「什么都点不动」。
--
-- 用 LIKE 'crm.customers.%' 扫**整个集合**，而不是只补 read 一条：
--   · 覆盖本迁移登记的全部 3 个动作；
--   · 幂等 —— 重复执行不产生重复行（ON CONFLICT DO NOTHING）。
--
-- 与 V3 / V8 / V104 / V330 / V378 / V380 / V382 / V418 同口径：租户所有者始终拥有全部页面权限。
--
-- ---------------------------------------------------------------------------
-- 五、幂等
-- ---------------------------------------------------------------------------
--
-- 三段式全部带 ON CONFLICT DO NOTHING：同一段 SQL 跑两次不报错、不产生重复行。
-- ===========================================================================

-- ---------------------------------------------------------------------------
-- 1. 页面资源（菜单入口）
-- ---------------------------------------------------------------------------
INSERT INTO page_resource(code,name) VALUES ('crm.customers','客户列表')
ON CONFLICT (code) DO NOTHING;

-- ---------------------------------------------------------------------------
-- 2. 权限码（3 个动作）
-- ---------------------------------------------------------------------------
INSERT INTO permission
SELECT 'crm.customers.'||action,'crm.customers',action
FROM unnest(ARRAY['read','update','pii.read']::text[]) action
ON CONFLICT (code) DO NOTHING;

-- ---------------------------------------------------------------------------
-- 3. 存量 OWNER 补权（覆盖 crm.customers.% 整个集合）
-- ---------------------------------------------------------------------------
INSERT INTO role_permission SELECT r.tenant_id,r.id,p.code FROM role r CROSS JOIN permission p
 WHERE r.code='OWNER' AND p.code LIKE 'crm.customers.%' ON CONFLICT DO NOTHING;
