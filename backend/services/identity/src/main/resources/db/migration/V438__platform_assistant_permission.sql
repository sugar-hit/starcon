-- ===========================================================================
-- V438 · platform_assistant_permission —— 18.4.1.1「对话助手」的权限码登记
-- ===========================================================================
--
-- 蓝图 18「集成开放与智能自动化」→ 18.4「AI 与智能」→ 18.4.1「智能问答」→ 18.4.1.1。
--
-- ---------------------------------------------------------------------------
-- 一、为什么需要这个迁移
-- ---------------------------------------------------------------------------
--
-- platform 服务的 AssistantController 用
--     access.require(bearer, "platform.assistant." + permission)
-- 强制鉴权，端点实际用到 2 个动作：read / create。
--
-- 但 identity 服务的 permission 表里**从来没有注册过 platform.assistant 任何一行** ——
-- 而 role_permission.permission_code 有指向 permission(code) 的外键 ——
-- 于是「没有任何角色可能持有 platform.assistant.read」，
-- 这些端点在真实环境里恒 403。
--
-- （与 V378 登记 platform.app.*、V380 登记 platform.text.*、V419 登记
--   platform.automation_rule.*、V429 / V430 登记 platform.ai-diagnosis.* /
--   platform.ai-effect.* 的缺口**完全同构**。）
--
-- 本迁移只做一件事：把这 2 个码登记进 identity 的权限码表。
--
-- ---------------------------------------------------------------------------
-- 二、登记哪几个码
-- ---------------------------------------------------------------------------
--
--   platform.assistant.read   读能力声明 / 受控意图目录 / 会话历史（含明细链接）
--   platform.assistant.create 提一个问题（写一轮问答台账 + 明细依据）
--
-- 刻意**只**登记这 2 个动作：没有端点的权限码不注册
-- （与 identity V104 / V53 / V330 / V378 / V380 / V419 同一纪律）。
--
-- 「读」与「提」是**两个独立的码**，理由与 18.2.3.1 的「配置 / 同步」同源：
-- 提问会写台账（问答历史 + 明细依据），是**写动作**；
-- 而读会话历史是读动作。能看别人的会话不等于能替别人提问。
--
-- ⚠️ **本车道不登记「执行 / 下钻」权限码** —— 明细链接指向的是各域**已交付的页面**
-- （13.4.1.1 / 13.5.1.1 / 13.2 / 12.7.2.1 / 13.3.1.2 / 15.6.2.1 / 9.4.1.1），
-- 那些页面的权限码归各自的域，本迁移不越界登记。
--
-- ---------------------------------------------------------------------------
-- 三、为什么 page_code 取 platform.assistant
-- ---------------------------------------------------------------------------
--
-- permission.page_code 有外键指向 page_resource(code)，所以必须先插页面行。
--
-- page_resource 对应**菜单入口**，不是动作。
-- 「对话助手」是 18.4.1.1 的**同一个页面**（提问 + 意图目录 + 会话历史在同一处），
-- 不是一个动作一个页面。
--
-- 前缀取 platform.assistant：权限码由 **platform 服务**消费
-- （platform.assistant.read），与 catalog.spu / warehouse.facilities /
-- platform.app / platform.text / platform.automation_rule 的「服务名.页面」口径一致。
--
-- ⚠️ **不碰 channel.* 与 platform.* 的既有前缀**：本迁移**只**动
--   platform.assistant.%，与其它车道互不覆盖。
--
-- ---------------------------------------------------------------------------
-- 四、为什么必须给存量 OWNER 补权（这是本迁移最容易漏的一步）
-- ---------------------------------------------------------------------------
--
-- 新建子租户由 create_child（V47）把 permission 表里的**全部**权限码授给 OWNER，
-- 所以新租户自动就有这 2 个码 —— 但**存量租户**的 OWNER 角色是在这 2 个码登记之前建的，
-- 不会自动获得它们 ⇒ 迁移上线后这些租户会突然「什么都点不动」。
--
-- 用 LIKE 'platform.assistant.%' 扫**整个集合**，而不是只补 read 一条：
--   · 覆盖本迁移登记的全部 2 个动作；
--   · 幂等 —— 重复执行不产生重复行（ON CONFLICT DO NOTHING）。
--
-- 与 V3 / V8 / V104 / V330 / V378 / V380 / V419 / V430 同口径：租户所有者始终拥有全部页面权限。
--
-- ---------------------------------------------------------------------------
-- 五、幂等
-- ---------------------------------------------------------------------------
--
-- 三段式全部带 ON CONFLICT DO NOTHING：同一段 SQL 跑两次不报错、不产生重复行。
-- ===========================================================================

-- ---------------------------------------------------------------------------
-- 1. 页面资源（菜单入口）
-- ---------------------------------------------------------------------------
INSERT INTO page_resource(code,name) VALUES ('platform.assistant','对话助手')
ON CONFLICT (code) DO NOTHING;

-- ---------------------------------------------------------------------------
-- 2. 权限码（2 个动作）
-- ---------------------------------------------------------------------------
INSERT INTO permission SELECT 'platform.assistant.'||action,'platform.assistant',action
FROM unnest(ARRAY['read','create']::text[]) action
ON CONFLICT (code) DO NOTHING;

-- ---------------------------------------------------------------------------
-- 3. 存量 OWNER 补权（覆盖 platform.assistant.% 整个集合）
-- ---------------------------------------------------------------------------
INSERT INTO role_permission SELECT r.tenant_id,r.id,p.code FROM role r CROSS JOIN permission p
 WHERE r.code='OWNER' AND p.code LIKE 'platform.assistant.%' ON CONFLICT DO NOTHING;
